  var LANGUAGES = ['system', 'zh', 'en'];

  // setting：system | zh | en；跟随系统时，系统语言是中文就用中文，否则用英文
  function resolve(setting, systemLocale) {
    if (setting === 'zh' || setting === 'en') return setting;
    return /^zh/i.test(String(systemLocale || '')) ? 'zh' : 'en';
  }

  function create(lang) {
    var table = STRINGS[lang] || STRINGS.zh;
    function t(key, vars) {
      var s = key in table ? table[key] : STRINGS.zh[key];
      if (s == null) return key;
      if (typeof s === 'function') return s(vars || {});
      return vars ? s.replace(/\{(\w+)\}/g, function (m, k) { return k in vars ? vars[k] : m; }) : s;
    }
    t.lang = STRINGS[lang] ? lang : 'zh';
    t.locale = t.lang === 'en' ? 'en-US' : 'zh-CN';
    return t;
  }

  return { LANGUAGES: LANGUAGES, STRINGS: STRINGS, resolve: resolve, create: create };
